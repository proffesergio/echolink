import '../src/env.mjs';
import {chromium} from 'playwright';
import {mkdir} from 'node:fs/promises';
const response=await fetch('http://127.0.0.1:8787/admin/api/ticket',{method:'POST',headers:{Authorization:'Bearer '+process.env.WORKER_API_KEY}});
if(!response.ok)throw new Error('Dashboard login failed');
const {ticket}=await response.json();
const browser=await chromium.launch({channel:'msedge',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000}}),errors=[];
page.on('pageerror',e=>errors.push(e.message));
try{
  await page.goto('http://127.0.0.1:8787/admin');
  await page.getByRole('button',{name:'Pages & models',exact:true}).click();
  await page.getByRole('heading',{name:'Sign in to EchoLink'}).waitFor();
  if(await page.locator('#mode').textContent()==='Connecting')throw new Error('Stuck connecting');
  await page.getByRole('button',{name:'News feeds',exact:true}).click();
  await page.getByRole('heading',{name:'Sign in to EchoLink'}).waitFor();
  await page.route('**/admin/api/state',async route=>{await new Promise(resolve=>setTimeout(resolve,800));await route.continue();});
  await page.goto(`http://127.0.0.1:8787/admin#ticket=${ticket}`);
  await page.waitForFunction(()=>document.querySelector('#mode').textContent.includes('DRY RUN'));
  await page.getByRole('button',{name:'Overview',exact:true}).click();
  await page.getByRole('heading',{name:'One pipeline. Every page.'}).waitFor({timeout:30000});
  await page.getByRole('button',{name:'Pages & models',exact:true}).click();
  await page.getByLabel('Source Comment Delay Minutes').waitFor();
  if(await page.getByLabel('Minimum Minutes Between Posts').inputValue()!=='30')throw new Error('Missing posting policy default');
  await page.getByRole('button',{name:'News feeds',exact:true}).click();
  await page.waitForFunction(()=>document.querySelectorAll('[data-action="pick-feed"]').length>=20);
  if(await page.locator('[data-action="pick-feed"]').count()<20)throw new Error('Bangla source catalog not visible');
  await page.getByRole('button',{name:'Connections',exact:true}).click();
  if(await page.locator('input[type="password"]').count()!==2)throw new Error('Token inputs not protected');
  await page.getByRole('button',{name:'Review queue',exact:true}).click();
  await page.locator('summary').filter({hasText:'Skipped & failed ingestion events'}).click();
  await page.getByRole('heading',{name:'Skipped & failed ingestion events'}).waitFor();
  await page.getByRole('button',{name:'Settings',exact:true}).click();
  await page.getByRole('heading',{name:'Dashboard password',exact:true}).waitFor();
  await page.getByLabel('embeddingURL').waitFor();
  await page.getByLabel('n8nAPIKey').waitFor();
  if(await page.getByLabel('databaseURL',{exact:true}).inputValue()!=='')throw new Error('Database secret exposed');
  await page.getByRole('button',{name:'Workflow',exact:true}).click();
  await page.getByRole('heading',{name:'One connected n8n workflow'}).waitFor();
  await page.getByRole('button',{name:'Overview',exact:true}).click();
  await mkdir('.codex/logs',{recursive:true});
  await page.screenshot({path:'.codex/logs/admin-overview.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  if(await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth))throw new Error('Mobile layout overflows');
  if(errors.length)throw new Error('Browser errors: '+errors.join('; '));
  await page.reload();await page.getByRole('heading',{name:'One pipeline. Every page.'}).waitFor();
  await page.route('**/admin/api/state',route=>route.fulfill({status:503,contentType:'application/json',body:JSON.stringify({error:'Simulated service outage'})}));
  await page.getByRole('button',{name:'Refresh',exact:true}).click();
  await page.getByText('Simulated service outage',{exact:true}).waitFor();
  await page.getByRole('button',{name:'Settings',exact:true}).click();
  await page.getByLabel('airtableBaseId').waitFor();
  await page.getByRole('button',{name:'Sign out',exact:true}).click();
  await page.getByRole('heading',{name:'Sign in to EchoLink'}).waitFor();
  if(errors.length)throw new Error('Browser errors: '+errors.join('; '));
  console.log('PASS browser: logged-out navigation, delayed loading, owner login, reload session, page policies, 20+ feeds, secret masking, settings, connected workflow, service outage recovery, logout, mobile layout; no JavaScript errors.');
}finally{await browser.close();}
